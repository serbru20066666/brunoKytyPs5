# Regenerates src/fuente_poppins.h from tools/Poppins-Medium.ttf.
d = open('tools/Poppins-Medium.ttf', 'rb').read()
lines = ['// Poppins Medium (SIL Open Font License 1.1, Indian Type Foundry), embedded: generated by tools/fuente.py.',
         '#pragma once', '', f'inline constexpr unsigned int kPoppinsSize = {len(d)};',
         'alignas(4) inline constexpr unsigned char kPoppins[] = {']
for i in range(0, len(d), 24):
    lines.append('    ' + ','.join(str(b) for b in d[i:i + 24]) + ',')
lines.append('};')
open('src/fuente_poppins.h', 'w', newline='\n').write('\n'.join(lines) + '\n')
